    /** Clave completa: normalización del emparejador sin palabras vacías; conserva las palabras de material. */
    fun fullKey(text: String): String =
        words(text).filter { it !in IMPORT_STOP_WORDS }.joinToString(" ") { ExerciseMatchLexicon.stem(it) }

    /** Clave sin palabras de material: lo que queda cuando el material elige la configuración. */
    fun coreKey(text: String): String =
        words(text).filter { it !in IMPORT_STOP_WORDS && it !in MATERIAL_WORDS }
            .joinToString(" ") { ExerciseMatchLexicon.stem(it) }

    /** Alias de un nombre: primero por clave completa («bodyweight squat») y luego sin material («barbell squat»). */
    fun lookup(name: String): ImportExerciseAlias? {
        byKey[fullKey(name)]?.let { return it }
        val core = coreKey(name)
        if (core.isEmpty()) return null
        // «press» con mancuernas: banca o de hombros según la hoja; sin alias, sale «Elegir».
        if (core == "press" && words(name).any { it in AMBIGUOUS_PRESS_MATERIALS }) return null
        return byKey[core]
    }

    private val byKey: Map<String, ImportExerciseAlias> =
        entries.associate { (phrase, alias) -> fullKey(phrase) to alias }

    private fun words(text: String): List<String> =
        ExerciseMatchLexicon.normalize(text).split(' ').filter { it.isNotEmpty() }
}

private fun alias(definitionId: String) = ImportExerciseAlias(definitionId)

private fun withEquipment(definitionId: String, equipmentId: String) =
    ImportExerciseAlias(definitionId, equipmentId = equipmentId)

private fun withConfiguration(definitionId: String, configurationId: String) =
    ImportExerciseAlias(definitionId, configurationId = configurationId)
